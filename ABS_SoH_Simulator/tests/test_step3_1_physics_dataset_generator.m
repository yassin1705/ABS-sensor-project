% TEST_STEP3_1_PHYSICS_DATASET_GENERATOR
% Verifie la dynamique glissement/blocage et le CSV multi-simulations.

projectRoot = fileparts(fileparts(mfilename("fullpath")));
addpath(fullfile(projectRoot, "core"));

outputFolder = fullfile(tempdir, "abs_physics_dataset_tests");
generator = ExperimentDatasetGenerator( ...
    fullfile(projectRoot, "scenarios", "scenario_physics_dataset.json"), ...
    outputFolder, 2026);

distribution = struct( ...
    "normal_rolling", 0.25, ...
    "wheel_lock", 0.25, ...
    "sliding", 0.25, ...
    "random", 0.25);

[outputPath, data, manifest] = generator.generate(distribution, 4, 3.0);

assert(isfile(outputPath), "Le CSV agrege doit etre cree.");
assert(height(data) == 4 * 300, ...
    "Toutes les simulations doivent avoir exactement 300 pas.");
assert(height(manifest) == 4, ...
    "Le manifeste doit contenir une ligne par simulation.");
assert(numel(unique(data.simulation_id)) == 4, ...
    "Le CSV doit contenir quatre identifiants de simulation.");

requiredColumns = [ ...
    "requested_phenomenon", ...
    "wheel_ground_speed_FL_mps", ...
    "wheel_peripheral_speed_FL_mps", ...
    "wheel_slip_ratio_FL", ...
    "normal_load_FL_N", ...
    "wheel_locked_FL"];
assert(all(ismember(requiredColumns, ...
    string(data.Properties.VariableNames))), ...
    "Le CSV physique ne contient pas toutes les colonnes attendues.");

lockRow = manifest.requested_phenomenon == "wheel_lock";
slidingRow = manifest.requested_phenomenon == "sliding";
normalRow = manifest.requested_phenomenon == "normal_rolling";
assert(nnz(lockRow) == 1 && manifest.any_wheel_locked(lockRow), ...
    "La recette wheel_lock doit produire un blocage.");
assert(nnz(slidingRow) == 1 && ...
    manifest.maximum_abs_slip(slidingRow) > 0.05 && ...
    ~manifest.any_wheel_locked(slidingRow), ...
    "La recette sliding doit glisser sans bloquer.");
assert(nnz(normalRow) == 1 && ...
    manifest.maximum_abs_slip(normalRow) < 0.05 && ...
    ~manifest.any_wheel_locked(normalRow), ...
    "La recette normal_rolling doit rester en roulement normal.");

normalLoads = data{:, { ...
    'normal_load_FL_N', 'normal_load_FR_N', ...
    'normal_load_RL_N', 'normal_load_RR_N'}};
loadSum = sum(normalLoads, 2);
assert(max(abs(loadSum - 1400 * 9.81)) < 1e-6, ...
    "La somme des charges verticales doit rester egale au poids.");

fprintf("Test dataset physique reussi : %d lignes, %d simulations.\n", ...
    height(data), height(manifest));
