% TEST_BRAKING_DATASET_GENERATOR
% Verifie les contraintes et l'ecriture progressive du dataset freinage.

projectRoot = fileparts(fileparts(mfilename("fullpath")));
addpath(fullfile(projectRoot, "core"));

outputFolder = fullfile(tempdir, "abs_braking_dataset_tests");
generator = BrakingDatasetGenerator( ...
    fullfile(projectRoot, "scenarios", "scenario_physics_dataset.json"), ...
    outputFolder, 4200);

[outputPath, manifestPath, manifest] = generator.generate( ...
    8, 2.0, ChunkSize=2, ProgressEvery=8);

assert(isfile(outputPath), "Le CSV temporel doit etre cree.");
assert(isfile(manifestPath), "Le manifeste doit etre cree.");
assert(height(manifest) == 8, ...
    "Le manifeste doit contenir huit simulations.");
manifestFromCsv = readtable(manifestPath, TextType="string");
assert(height(manifestFromCsv) == 8, ...
    "Le manifeste CSV doit contenir huit simulations.");
assert(all(manifest.initial_speed_kmh >= 40 & ...
    manifest.initial_speed_kmh <= 100), ...
    "Les vitesses initiales doivent rester entre 40 et 100 km/h.");
assert(all(manifest.minimum_brake > 0), ...
    "Le frein doit etre strictement positif des le debut.");
assert(all(manifest.minimum_abs_steering_wheel_deg >= 10 - 1e-9), ...
    "Le braquage doit toujours respecter la borne de 10 degres.");

data = readtable(outputPath, TextType="string");
assert(height(data) == 8 * 200, ...
    "Le CSV doit contenir exactement 200 pas par simulation.");
assert(numel(unique(data.simulation_id)) == 8, ...
    "Le CSV doit contenir huit identifiants de simulation.");
assert(all(data.brake > 0), ...
    "Toutes les commandes de freinage doivent etre positives.");
assert(all(abs(data.steering_wheel_angle_deg) >= 10 - 1e-9), ...
    "Toutes les commandes de braquage doivent etre non nulles.");
assert(any(data.requested_phenomenon == "sliding" & ...
    data.observed_phenomenon == "sliding"), ...
    "La recette sliding doit produire des fenetres de glissement.");

requiredColumns = [ ...
    "wheel_speed_ecu_FL_mps", "wheel_speed_ecu_FR_mps", ...
    "wheel_speed_ecu_RL_mps", "wheel_speed_ecu_RR_mps", ...
    "observed_phenomenon"];
assert(all(ismember(requiredColumns, ...
    string(data.Properties.VariableNames))), ...
    "Le CSV ne contient pas toutes les colonnes attendues.");

fprintf("Test generateur freinage reussi : %d lignes.\n", height(data));
