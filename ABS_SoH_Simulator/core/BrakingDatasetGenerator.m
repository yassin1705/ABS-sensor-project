        function writeTableChunk(~, chunk, outputPath, firstWrite)
            if firstWrite
                writetable(chunk, outputPath);
            else
                writetable(chunk, outputPath, ...
                    WriteMode="append", WriteVariableNames=false);
            end
        end

        function result = appendTable(~, current, addition)
            if isempty(current)
                result = addition;
            else
                result = [current; addition];
            end
        end

        function configPath = writeTemporaryConfig(~, rawConfig)
            configPath = string(tempname) + ".json";
            fileId = fopen(configPath, "w");
            assert(fileId >= 0, ...
                "Impossible de creer la configuration temporaire.");
            closeFile = onCleanup(@()fclose(fileId));
            fwrite(fileId, jsonencode(rawConfig, PrettyPrint=true), "char");
            clear closeFile
        end

        function deleteTemporaryConfig(~, configPath)
            if isfile(configPath)
                delete(configPath);
            end
        end

        function value = uniform(~, stream, lower, upper)
            value = lower + (upper - lower) * rand(stream);
        end

        function value = pick(~, stream, values)
            value = values(randi(stream, numel(values)));
        end
